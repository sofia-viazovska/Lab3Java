package skilift;

/**
 * Емулює апаратний зчитувач турнікета. За умовою на картці зберігаються всі
 * дані (тип, термін дії, кількість поїздок тощо), але джерелом істини є
 * система реєстрації, тому зчитувач повертає лише ідентифікатор картки,
 * а решту даних турнікет бере з реєстру (SkiPassRegistry) за цим ідентифікатором.
 */
public interface CardReader {

    String readCardId() throws CardReadException;
}
